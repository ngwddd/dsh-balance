// ── 音量 ──────────────────────────────────────────────
// System.Media.SoundPlayer 没有音量参数，所以按当前音量把 WAV 预衰减一份再播：
// 播放仍是零延迟的本地文件，调音量只是换一个缓存文件。
// ★ 配置读写统一走 notifyConfig() / saveNotifyConfig()：
//   旧实现有一个只写 { volume } 的 saveChimeVolume()，会把手动设的
//   minTurnMs / lowThreshold 一起冲掉（2026-10-26 代码审查发现，已删）。

function wavDataRange(buf) {
  let offset = 12;
  while (offset + 8 <= buf.length) {
    const id = buf.toString('ascii', offset, offset + 4);
    const size = buf.readUInt32LE(offset + 4);
    if (id === 'data') {
      const at = offset + 8;
      return { at, len: Math.min(size, buf.length - at) };
    }
    offset += 8 + size + (size % 2);
  }
  return null;
}

function peakOf(buf, data) {
  let peak = 0;
  for (let i = data.at; i + 1 < data.at + data.len; i += 2) {
    const a = Math.abs(buf.readInt16LE(i));
    if (a > peak) peak = a;
  }
  return peak;
}

function renderChime(buf, gain) {
  const data = wavDataRange(buf);
  if (!data) return null;
  const out = Buffer.from(buf);
  for (let i = data.at; i + 1 < data.at + data.len; i += 2) {
    const scaled = Math.round(out.readInt16LE(i) * gain);
    out.writeInt16LE(Math.max(-32768, Math.min(32767, scaled)), i);
  }
  return out;
}

// 系统通知音本身很轻：notify.wav 峰值只有 0.07（约 -23 dBFS），
// 滑块拉满也只是原音量，所以先归一化到接近满刻度（-0.4 dBFS），再乘滑块。
function chimeFileFor(src, volume) {
  if (!Number.isFinite(volume) || volume <= 0) return null;
  const dir = chimeCacheDir();
  const base = src.replace(/^.*[\\/]/, '').replace(/\.[^.]+$/, '').replace(/[^A-Za-z0-9]+/g, '-');
  const target = join(dir, `${base}-v2-${volume}.wav`);
  if (existsSync(target)) return target;
  try {
    mkdirSync(dir, { recursive: true });
    const buf = readFileSync(src);
    const data = wavDataRange(buf);
    if (!data) return src;
    const peak = peakOf(buf, data);
    if (!peak) return src;
    const normalize = Math.min(16, (0.95 * 32767) / peak);
    const out = renderChime(buf, normalize * (volume / 100));
    if (!out) return src;
    writeFileSync(target, out);
    for (const name of readdirSync(dir)) {
      if (name.startsWith(base + '-') && join(dir, name) !== target) {
        try { unlinkSync(join(dir, name)); } catch { /* ignore */ }
      }
    }
    return target;
  } catch {
    return src;
  }
}


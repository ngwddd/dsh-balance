/**
 * sound: 要不要出声（调用方已判断开关/时长）；flash: 要不要闪任务栏。
 * 两个都为 false 时什么都不做，不启动进程。
 */
function notify(options = {}) {
  const settings = notifyConfig();
  // force: 试听用——开关关着也要能出声；日常提醒仍受开关控制
  const wantSound = options.sound === true && (options.force === true || !chimeDisabled());
  const wav = wantSound ? chimeFileFor(options.src || CHIME_OK, settings.volume) : null;
  const flash = options.flash === true;
  if (!wav && !flash) return false;
  const script = ensureNotifyScript();
  if (!script) return false;
  const args = ['-NoProfile', '-NonInteractive', '-WindowStyle', 'Hidden', '-ExecutionPolicy', 'Bypass', '-File', script];
  if (wav) args.push('-Wav', wav);
  if (flash) args.push('-Flash');
  try {
    const child = spawn('powershell.exe', args, { stdio: 'ignore', windowsHide: true });
    child.on('error', () => {});
    child.unref();
    return true;
  } catch {
    return false;
  }
}

